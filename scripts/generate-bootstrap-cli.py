#!/usr/bin/env python3
"""Generate the bootstrap CLI reference from its single declarative table."""

from __future__ import annotations

import argparse
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "src" / "bootstrap" / "cli" / "command_spec.def"
README = ROOT / "src" / "bootstrap" / "cli" / "README.md"


def split_fields(text: str) -> list[str]:
    fields: list[str] = []
    begin = 0
    quoted = False
    escaped = False
    for index, char in enumerate(text):
        if quoted:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                quoted = False
        elif char == '"':
            quoted = True
        elif char == ",":
            fields.append(text[begin:index].strip())
            begin = index + 1
    fields.append(text[begin:].strip())
    return fields


def c_string(value: str) -> str:
    if value == "NULL":
        return ""
    parsed = ast.literal_eval(value)
    if not isinstance(parsed, str):
        raise ValueError(f"expected C string, got {value!r}")
    return parsed


def load_spec() -> tuple[list[dict[str, object]], list[dict[str, object]]]:
    commands: list[dict[str, object]] = []
    options: list[dict[str, object]] = []
    macro = re.compile(r"^VITTE_CLI_(COMMAND|OPTION)\((.*)\)$")
    for raw in SPEC.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        match = macro.match(line)
        if not match:
            continue
        kind, payload = match.groups()
        fields = split_fields(payload)
        if kind == "COMMAND":
            if len(fields) != 5:
                raise ValueError(f"bad command row: {line}")
            commands.append({
                "name": c_string(fields[0]),
                "summary": c_string(fields[1]),
                "requires_input": fields[2] == "true",
                "forwards_arguments": fields[3] == "true",
                "id": fields[4],
            })
        else:
            if len(fields) != 4:
                raise ValueError(f"bad option row: {line}")
            options.append({
                "spelling": c_string(fields[0]),
                "value": c_string(fields[1]),
                "summary": c_string(fields[2]),
                "id": fields[3],
            })
    if not commands or not options:
        raise ValueError("CLI table is empty")
    return commands, options


def markdown_cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def option_aliases(spelling: str) -> list[str]:
    return [alias.strip() for alias in spelling.split(",")]


def render() -> str:
    commands, options = load_spec()
    lines = [
        "<!-- Generated by scripts/generate-bootstrap-cli.py. -->",
        "<!-- Edit src/bootstrap/cli/command_spec.def, then run `make -C src docs`. -->",
        "",
        "# Vitte bootstrap CLI",
        "",
        "This reference, `vitte --help`, and scripts produced by",
        "`vitte completion` use the same declarative command table.",
        "",
        "## Commands",
        "",
        "| Command | Input | Summary |",
        "| --- | --- | --- |",
    ]
    for command in commands:
        command_name = str(command["name"])
        name = f"`{command_name}`"
        if command_name == "compile":
            name += " (default)"
        if command_name == "completion":
            entry = "`bash`, `zsh`, or `fish`"
        elif command_name in {"help", "version"}:
            entry = "none"
        elif command_name == "explain":
            entry = "public code (for example, `E0501`)"
        else:
            entry = "`.vit` file"
        lines.append(
            f"| {name} | {entry} | {markdown_cell(str(command['summary']))} |"
        )
    lines += [
        "",
        "The `--` separator forwards the remaining arguments to the `run` program.",
        "",
        "## Options",
        "",
        "| Option | Description |",
        "| --- | --- |",
    ]
    for option in options:
        aliases = ", ".join(f"`{markdown_cell(alias)}`" for alias in option_aliases(str(option["spelling"])))
        lines.append(f"| {aliases} | {markdown_cell(str(option['summary']))} |")
    lines += [
        "",
        "The `--stop-after-*` options are mutually exclusive. `run` cannot be",
        "combined with intermediate output or a pipeline stop. The pairs",
        "`--quiet`/`--verbose`, `--color`/`--no-color`, and",
        "`--validate-utf8`/`--no-validate-utf8` are also mutually exclusive.",
        "The CLI validates these conflicts before starting the driver.",
        "",
        "## Configuration and precedence",
        "",
        "Configuration values are merged in this order, from lowest to highest precedence:",
        "",
        "```text",
        "defaults < vitte.toml/.vitte/config < environment < command line",
        "```",
        "`VITTE_CONFIG_FILE` selects an explicit configuration file. Environment",
        "variables use uppercase `VITTE_<KEY>` names, with hyphens replaced by",
        "underscores (for example, `VITTE_MAX_ERRORS` and",
        "`VITTE_DIAGNOSTIC_FORMAT`). CLI values take precedence over earlier",
        "sources. Configuration is merged and validated once before the pipeline.",
        "`VITTE_MODULE_PATH` adds module search roots separated by `:`.",
        "",
        "## Diagnostics",
        "",
        "The `terminal`, `json`, `sarif`, and `lsp` formats share public codes,",
        "phases, severities, type contexts, help, causes, and source locations.",
        "JSON and SARIF retain source byte offsets. LSP adds a UTF-16 range and",
        "keeps raw offsets in `data`.",
        "",
        "`vitte explain CODE` accepts public codes in the registry",
        "(`Edddd`, `Wdddd`, `Ndddd`, and `Hdddd`). Add `--diagnostic=json`",
        "to print the structured explanation.",
        "",
        "## Shell completion",
        "",
        "```sh",
        "vitte completion bash > vitte.bash",
        "vitte completion zsh > _vitte",
        "vitte completion fish > ~/.config/fish/completions/vitte.fish",
        "```",
        "The three scripts are generated at runtime from the same table as the",
        "help text. Short and long aliases (such as `-h`/`--help` and",
        "`-o`/`--output`) are included automatically.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not README.exists() or README.read_text(encoding="utf-8") != generated:
            print(f"[bootstrap-cli] stale: {README}")
            return 1
        print("[bootstrap-cli] OK")
        return 0
    README.write_text(generated, encoding="utf-8")
    print(f"[bootstrap-cli] wrote {README}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
