#!/usr/bin/env python3
"""Generate and verify the bootstrap token/diagnostic/option reference."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
GRAMMAR = ROOT / "grammar" / "vitte.ebnf"
LEXER = ROOT / "src" / "bootstrap" / "lexer" / "lexer.c"
REGISTRY = ROOT / "src" / "bootstrap" / "diagnostic" / "registry.c"
CLI_SPEC = ROOT / "src" / "bootstrap" / "cli" / "command_spec.def"
OUTPUT = ROOT / "docs" / "bootstrap" / "generated-reference.md"


def terminals() -> tuple[list[str], list[str]]:
    grammar = re.sub(r"\(\*.*?\*\)", "", GRAMMAR.read_text(), flags=re.S)
    reserved = re.search(r"reserved_keyword\s*::=(.*?);", grammar, flags=re.S)
    keywords = sorted(
        set(
            re.findall(
                r'"([^"\\]*(?:\\.[^"\\]*)*)"', reserved.group(1)
            )
        )
        if reserved
        else set()
    )
    lexer = LEXER.read_text()
    operators = sorted(set(text for text, _ in re.findall(
        r'VITTE_OP\("([^"\\]+)",\s*(VITTE_TOKEN_[A-Z0-9_]+)\)', lexer
    )))
    return keywords, operators


def diagnostics() -> list[str]:
    text = REGISTRY.read_text()
    return sorted(set(re.findall(
        r'"(VITTE_[A-Z0-9_]+_[EWN]_[A-Z0-9_]+)"', text
    )))


def options() -> list[str]:
    text = CLI_SPEC.read_text()
    found = set()
    for spelling in re.findall(r'VITTE_CLI_OPTION\("([^"\\]*(?:\\.[^"\\]*)*)"', text):
        for alias in spelling.split(","):
            token = alias.strip().split()[0].split("=", 1)[0]
            if token.startswith("-") and token != "--":
                found.add(token)
    return sorted(found)


def commands() -> list[str]:
    text = CLI_SPEC.read_text()
    return sorted(set(re.findall(r'VITTE_CLI_COMMAND\("([^"\\]+)"', text)))


def render() -> str:
    keywords, operators = terminals()
    codes = diagnostics()
    opts = options()
    command_names = commands()
    lines = [
        "<!-- Generated by scripts/generate-bootstrap-reference.py. -->",
        "<!-- Run `make docs` after changing grammar, diagnostics or CLI. -->",
        "",
        "# Bootstrap reference",
        "",
        "This file is generated from the canonical EBNF and bootstrap sources.",
        "",
        "## Keywords",
        "",
        "| Keyword |",
        "| --- |",
        *[f"| `{item}` |" for item in keywords],
        "",
        "## Operators",
        "",
        "| Operator |",
        "| --- |",
        *[f"| `{item}` |" for item in operators],
        "",
        "## Commands",
        "",
        "| Command |",
        "| --- |",
        *[f"| `{item}` |" for item in command_names],
        "",
        "## Diagnostic codes",
        "",
        "| Code |",
        "| --- |",
        *[f"| `{item}` |" for item in codes],
        "",
        "## Command-line options",
        "",
        "| Option |",
        "| --- |",
        *[f"| `{item}` |" for item in opts],
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            print(f"[bootstrap-docs] stale: {OUTPUT}")
            return 1
        print("[bootstrap-docs] OK")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated)
    print(f"[bootstrap-docs] wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
