#!/usr/bin/env python3
"""Generate the pinned Unicode XID tables used by the bootstrap lexer.

Python's identifier predicate follows the Unicode XID_Start/XID_Continue
properties.  The generated header records the interpreter's Unicode database
version so a table change is explicit and reproducible.

The Unicode version is intentionally immutable in this script.  Updating it
is a language change: regenerate the table, update the C version contract and
review the identifier regression tests together.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import unicodedata


# Unicode data is a language/build input, not an implementation detail of the
# Python executable running this script.  Keep this value in sync with the
# checked-in table and the `UNICODE_DATA_VERSION` make variable.  A Python
# interpreter backed by another Unicode database must fail loudly instead of
# silently changing the lexer language.
PINNED_UNICODE_VERSION = "16.0.0"
GENERATOR_FORMAT_VERSION = 1


def ranges_for(predicate):
    ranges = []
    first = None
    previous = None
    for codepoint in range(0x110000):
        if predicate(chr(codepoint)):
            if first is None:
                first = codepoint
            elif codepoint != previous + 1:
                ranges.append((first, previous))
                first = codepoint
            previous = codepoint
    if first is not None:
        ranges.append((first, previous))
    return ranges


def emit_ranges(name, ranges):
    lines = [
        f"static const vitte_unicode_xid_range_t {name}[] = {{",
    ]
    for first, last in ranges:
        lines.append(f"    {{ UINT32_C(0x{first:06x}), UINT32_C(0x{last:06x}) }},")
    lines.extend(["};", ""])
    return lines


def render_table(version: str) -> str:
    version_parts = version.split(".")
    version_parts += ["0", "0"]
    major, minor, patch = (int(version_parts[i]) for i in range(3))
    starts = ranges_for(lambda character: character.isidentifier())
    continues = ranges_for(lambda character: ("a" + character).isidentifier())

    output = [
        "/* Generated by scripts/generate-unicode-xid.py. Do not edit. */",
        "#ifndef VITTE_UNICODE_XID_TABLE_H",
        "#define VITTE_UNICODE_XID_TABLE_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"#define VITTE_UNICODE_GENERATED_DATA_VERSION_MAJOR {major}u",
        f"#define VITTE_UNICODE_GENERATED_DATA_VERSION_MINOR {minor}u",
        f"#define VITTE_UNICODE_GENERATED_DATA_VERSION_PATCH {patch}u",
        f'#define VITTE_UNICODE_GENERATED_DATA_VERSION_STRING "{version}"',
        f"#define VITTE_UNICODE_GENERATED_FORMAT_VERSION {GENERATOR_FORMAT_VERSION}u",
        '#define VITTE_UNICODE_GENERATED_SOURCE "Python unicodedata XID properties"',
        "",
        "typedef struct vitte_unicode_xid_range {",
        "    uint32_t first;",
        "    uint32_t last;",
        "} vitte_unicode_xid_range_t;",
        "",
    ]
    output.extend(emit_ranges("vitte_unicode_xid_start_ranges", starts))
    output.extend(emit_ranges("vitte_unicode_xid_continue_ranges", continues))
    output.extend([
        "#define VITTE_UNICODE_XID_START_RANGE_COUNT \\",
        "    (sizeof(vitte_unicode_xid_start_ranges) / \\",
        "     sizeof(vitte_unicode_xid_start_ranges[0]))",
        "#define VITTE_UNICODE_XID_CONTINUE_RANGE_COUNT \\",
        "    (sizeof(vitte_unicode_xid_continue_ranges) / \\",
        "     sizeof(vitte_unicode_xid_continue_ranges[0]))",
        "",
        "#endif",
        "",
    ])
    return "\n".join(output)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument(
        "--expected-version",
        default=PINNED_UNICODE_VERSION,
        help="pinned Python Unicode database version (default: %(default)s)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the checked-in output without modifying it",
    )
    args = parser.parse_args()

    if args.expected_version != PINNED_UNICODE_VERSION:
        parser.error(
            "Unicode data version is frozen at %s; update the generator and "
            "the checked-in version contract together" % PINNED_UNICODE_VERSION)
    if unicodedata.unidata_version != args.expected_version:
        parser.error(
            "Python Unicode database is %s, expected pinned version %s" %
            (unicodedata.unidata_version, args.expected_version))

    generated = render_table(args.expected_version)
    if args.check:
        try:
            checked_in = args.output.read_bytes()
        except OSError as error:
            parser.error(f"cannot read {args.output}: {error}")
        if checked_in != generated.encode("utf-8"):
            parser.error(f"{args.output} is out of date; run unicode-table")
        return

    args.output.parent.mkdir(parents=True, exist_ok=True)
    # Use explicit UTF-8 and LF bytes on every host.  In particular, do not
    # let Windows translate line endings and make generated artifacts differ.
    with args.output.open("w", encoding="utf-8", newline="\n") as output:
        output.write(generated)


if __name__ == "__main__":
    main()
